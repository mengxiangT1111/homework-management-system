-- ============================================================
-- score 列精度升级：DECIMAL(5,2) → DECIMAL(6,2)
-- 原因：评分模板满分允许 1-1000，DECIMAL(5,2) 上限 999.99，
--       越界值会被 MySQL 拒绝写入（历史版本以 999.9 钳制绕过）。
--       DECIMAL(6,2) 上限 9999.99，覆盖模板满分上限后钳制已全部移除。
-- 适用：既有部署手工执行一次；新库由 sequelize 建表自动为 6,2。
-- 验证：node scripts/check-schema.js（模型与库列级比对）
-- ============================================================

ALTER TABLE `submissions`
  MODIFY COLUMN `score` DECIMAL(6,2) NULL COMMENT '分数（评分模板满分允许 1-1000，DECIMAL(6,2) 上限 9999.99）';
